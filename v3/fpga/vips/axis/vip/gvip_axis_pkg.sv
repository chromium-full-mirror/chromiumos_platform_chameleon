  // Class: core
  //
  // VIP core class
  // parameters must be consistent with interface instance parameters
  //
  // Parameters:
  //   N   - number of bytes of tdata
  //   I   - tid signal width
  //   D   - tdest signal width
  //   U_T - tuser type
  //   item_t - item type definition that matches interface -
  //            for some simulators is requied to have single point of type definition
  //            so in such case type can by pass to VIP
  class core #(int N = 1, int I = 1, int D = 1, type U_T = logic [0:0],
               type item_t = gvip_axis_item_pkg::item #(N, I, D, U_T))
               extends core_imp #(N, I, D, U_T, item_t) implements generic_ic;

    // Function: new
    //
    // Creates an instance of VIP core
    //
    // name     - instance name
    // vif      - axi stream interface handler
    // vclk     - clock interface handler
    // vip_type - one of VIPs type (MASTER/SLAVE/MONITOR)
    // vip_cfg  - optional cofiguration object (please check: gvip_config)
    //
    extern function new (string name, virtual gaxis_if #(.N(N), .I(I), .D(D), .U_T(U_T)) vif,
                         virtual gclk_if vclk, gvip_type_e vip_type, gvip_config vip_cfg = null);

    // Function: get_data_width
    //
    // Returns width of tdata in bits
    //
    extern virtual function int unsigned get_data_width();

    // Function: get_user_width
    //
    // Returns width of tuser in bits
    //
    extern virtual function int unsigned get_user_width();

    // Function: get_keep_width
    //
    // Returns width of tkeep in bits
    //
    extern virtual function int unsigned get_keep_width();

    // Function: get_vip_type
    //
    // Returns type of VIP
    //
    extern virtual function gvip_type_e get_vip_type();

    // Function: get_config
    //
    // Returns current configuration object
    //
    extern virtual function gvip_config get_config();

    // Function: add_ap2pkt
    //
    // Use this function to register object with analysis port interface implementation,
    // `write` function from this interface will be called with tlast occurrence
    // Any number of object can be registered but since item does not deliver clone functionality
    // the same object instance will be passed to all subscribers
    //
    extern virtual function void add_ap2pkt(analysis_port_ic #(item_t) ap);

    // Function: add_ap2transfer
    //
    // Use this function to register object with analysis port interface implementation,
    // `write` function from this interface will be called with each transfer occurrence
    // Any number of object can be registered but since item does not deliver clone functionality
    // the same object instance will be passed to all subscribers
    //
    extern virtual function void add_ap2transfer(analysis_port_ic #(item_t) ap);

    // Function: add_generic_ap2pkt
    //
    // Use this function to register object with generic analysis port interface implementation,
    // `write` function from this interface will be called with tlast occurrence
    // Any number of object can be registered but since item does not deliver clone functionality
    // the same object instance will be passed to all subscribers
    //
    extern virtual function void add_generic_ap2pkt(generic_analysis_port_ic ap);

    // Function: add_generic_ap2transfer
    //
    // Use this function to register object with generic analysis port interface implementation,
    // `write` function from this interface will be called with each transfer occurrence
    // Any number of object can be registered but since item does not deliver clone functionality
    // the same object instance will be passed to all subscribers
    //
    extern virtual function void add_generic_ap2transfer(generic_analysis_port_ic ap);

    // Function: set_policy
    //
    // Assign new handshake policy to VIP
    //
    // obj - policy object derived from gvip_policy_pkg::policy
    // do_randomize_policy - if set, VIP will call randomize method at policy object,
    //                       usefull when policy is created without declaration e.g.:
    //                       vip.set_policy(gvip_policy_pkg::random::create("def_random"), 1);
    // clone - in default VIP will clone policy to operate on it
    //
    extern virtual function void set_policy(policy obj, bit do_randomize_policy = 0, bit clone = 1);

    // Function: item2generic
    //
    // Converts concrete item of this VIP to generic one
    //
    extern virtual function generic_item item2generic(item_t arg);

    // Function: generic2item
    //
    // Converts generic item to concrete item of this VIP
    //
    extern virtual function item_t generic2item(generic_item arg);

    // Function: send_item
    //
    // This task sends data item to AxiStream interface
    // If some package is currently trasmited, new item will be added to queue
    // depending ~item.is_posted~ field task ends immediately or block
    // Supports any type derived from bitem (e.g.  ~generic_item~ or ~item_t~)
    //
    extern virtual task send_item(bitem item);

    // Function: run_phase
    //
    // Main VIPs service loop - run VIPs processing (must be called by test)
    // This task spawn internal processes and return immediately
    // Spawned processes are endless unless ~gvip_config::stop_vip~ is set
    //
    extern virtual task run_phase();

    // Function: clean
    //
    // This function clean VIP
    // Breakes any transfers at interface, clear all queues and any data structures
    //
    extern virtual function void clean();

  endclass : core



