  function core::new (string name,
                      virtual gaxis_if #(.N(N), .I(I), .D(D), .U_T(U_T)) vif,
                      virtual gclk_if vclk, gvip_type_e vip_type, gvip_config vip_cfg = null);
    this.name = name;
    this.vif = vif;
    this.vclk = vclk;
    this.vip_type = vip_type;
    this.cfg = vip_cfg;

    // user did not pass configuration, create default one
    if (cfg == null) cfg = new();

    // there is no report_id in configuration, create default one
    if (cfg.report_id.len() == 0) cfg.report_id = $sformatf("AXIS-VIP[%s]", name);

    // create monitor handshake object
    mon_hs = new(vif, vclk, cfg);

    // if configuratin request coverage, create it
    if (cfg.coverage) begin
      coverage = new(vif, vclk, name);
    end

    // depending on VIP type create master or slave handshake object
    if (vip_type == MASTER) begin
      hs = axis_master_hs #(N, I, D, U_T, item_t)::create(vif, vclk, cfg);
    end else if (vip_type == SLAVE) begin
      hs = axis_slave_hs #(N, I, D, U_T, item_t)::create(vif, vclk, cfg);
    end

    greporter::info(cfg.report_id, $sformatf("VIP '%s' CREATED", name));
  endfunction : new


  function generic_item core::item2generic(item_t arg);
    return gvip_axis_item_pkg::item_conv #(item_t)::item2generic(arg,
                                                    cfg.generic_item_squize_by_tkeep);
  endfunction : item2generic


  function core::item_t core::generic2item(generic_item arg);
    return gvip_axis_item_pkg::item_conv #(item_t)::generic2item(arg,
                                                    cfg.warn_resize_mismatch_from_generic,
                                                    cfg.generic_item_squize_by_tkeep);
  endfunction : generic2item


  function void core::add_ap2pkt(analysis_port_ic #(item_t) ap);
    mon_hs.add_ap2pkt(ap);
  endfunction : add_ap2pkt


  function void core::add_ap2transfer(analysis_port_ic #(item_t) ap);
    mon_hs.add_ap2transfer(ap);
  endfunction : add_ap2transfer


  function void core::add_generic_ap2pkt(generic_analysis_port_ic ap);
    mon_hs.add_ap2pkt(to_generic_item_ap #(item_t)::create(ap, cfg));
  endfunction : add_generic_ap2pkt


  function void core::add_generic_ap2transfer(generic_analysis_port_ic ap);
    mon_hs.add_ap2transfer(to_generic_item_ap #(item_t)::create(ap, cfg));
  endfunction : add_generic_ap2transfer


  function int unsigned core::get_data_width();
    return (vif.N * 8);
  endfunction : get_data_width


  function int unsigned core::get_user_width();
    return vif.U_T_WIDTH;
  endfunction : get_user_width


  function int unsigned core::get_keep_width();
    return vif.N;
  endfunction : get_keep_width


  function gvip_type_e core::get_vip_type();
    return vip_type;
  endfunction : get_vip_type


  function void core::set_policy(policy obj, bit do_randomize_policy = 0, bit clone = 1);
    if (do_randomize_policy && !obj.randomize()) begin
      greporter::error(cfg.report_id, $sformatf("Policy '%s' randomizastion issue", obj.name));
    end
    greporter::info(cfg.report_id, $sformatf("Policy set to %s [%s]", obj.get_name(),
                                                                      obj.get_type_name()));
    hs.set_policy(obj, clone);
  endfunction : set_policy


  task core::run_phase();
    // enable interface access
    case (vip_type)
      MASTER : vif.g_sim.force_as_master();
      SLAVE  : vif.g_sim.force_as_slave();
      default : begin end
    endcase

    // start core threads
    fork
      if (hs != null) begin
        while(!cfg.stop_vip) hs.start(cfg.transaction_in_reset);
      end

      while(!cfg.stop_vip) mon_hs.start(cfg.transaction_in_reset);
    join_none
  endtask : run_phase


  task core::send_item(bitem item);
    axis_master_hs #(N, I, D, U_T) m;

    if (vip_type != MASTER) begin // only master supports data send
      greporter::fatal(cfg.report_id, "This is not master VIP");
    end else if (!$cast(m, hs)) begin
      // VIP type is master but for some reason we can't cast
      // this should never happen
      greporter::fatal(cfg.report_id, "Wrong master VIP type");
    end

    // put requested item to queue, main thread from hs will take this item and put on bus
    m.put(item);

    // if item is not posted, block this task till item packet will be putted on bus
    if (!item.is_posted) begin
      @item.post;
    end
  endtask : send_item


  function gvip_config core::get_config();
    return cfg;
  endfunction : get_config


  function void core::clean();
    hs.clean();
    mon_hs.clean();
  endfunction : clean


endpackage : gvip_axis_pkg
