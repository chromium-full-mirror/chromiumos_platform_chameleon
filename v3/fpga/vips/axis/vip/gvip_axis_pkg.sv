  //////////////////////////////
  // Analysis ports interface //
  //////////////////////////////

  // Interface Class: generic_analysis_port_ic
  //
  // If Testbench operates generic_item, subscriber should implement this interface
  // Object with this interface can be register as Anaysis Port in VIP Core
  // Depending of registretion type write method will be called after each transfer
  // (core::add_generic_ap2transfer) or after whole packet (core::add_generic_ap2pkt)
  //
  interface class generic_analysis_port_ic;
    pure virtual function void write (input generic_item item);
  endclass : generic_analysis_port_ic


  // Interface Class: analysis_port_ic
  //
  // If Testbench operates item, subscriber should implement this interface
  // Object with this interface can be register as Anaysis Port in VIP Core
  // Depending of registretion type write method will be called after each transfer
  // (core::add_ap2transfer) or after whole packet (core::add_ap2pkt)
  //
  interface class analysis_port_ic #(type item_t = logic);
    pure virtual function void write (input item_t item);
  endclass : analysis_port_ic


  /////////////////////////////
  // VIP configuration types //
  /////////////////////////////

  // Enum: gvip_type_e
  //
  // This is used as VIP type choose
  // MASTER  - VIP will assert tvalid/tdata/tuser/tstrb/tkeep/tlast signals
  // SLAVE   - VIP will assert tready signal
  // MONITOR - VIP only observe bus and report transactions with analysis port
  //
  typedef enum logic [1:0] {
    MASTER,
    SLAVE,
    MONITOR
  } gvip_type_e;


  // Class: gvip_config
  //
  // Configuration object to configure VIP - can be pass to constructor
  //
  class gvip_config;

    // Variable: mask_data_with_keep_in_ap
    //
    // If this is set to 1, bytes in tdata with corresponding tkeep equal 0 will be cleared
    //
    bit mask_data_with_keep_in_ap = 0;

    // Variable: warn_resize_mismatch_from_generic
    //
    // If set to 0, no warning will be printed during conversion generic_item_t -> item_t
    // in case of size(generic_item_t::tdata) % N != 0
    //
    bit warn_resize_mismatch_from_generic = 1;

    // Variable: generic_item_squize_by_tkeep
    //
    // If this is set to 1, bytes of tdata  in generic_item with corresponding tkeep equal 0
    // will be removed - item will be have only valid bytes in tdata and all tkeep set to 1
    //
    bit generic_item_squize_by_tkeep = 0;

    // Variable: stop_vip
    //
    // If this is set to 1, VIP will not resume main thread after 'clear'
    // all VIPs thread will be stopped
    //
    bit stop_vip = 0;

    // Variable: transaction_in_reset
    //
    // In normal operation VIP operates only if reset in gclk_if is in not active state
    // If this variable is set, VIP does not take reset state into account
    //
    bit transaction_in_reset = 0;

    // Variable: report_id
    //
    // This string will be used as ID of messages generated by VIP
    //
    string report_id = "";

    // Variable: coverage
    //
    // Enable functional coverage counters
    // This value is taken into account only at vip core constructor
    //
    bit coverage = 0;

  endclass : gvip_config



