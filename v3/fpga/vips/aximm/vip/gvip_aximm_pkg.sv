  // Class: core
  //
  // VIP core class
  // parameters must be consistent with interface insance parameters
  //
  // Parameters:
  //   N      - number of bytes of tdata
  //   I      - id signal width
  //   A      - address signal width
  //   U_REQ  - awuser and aruser type
  //   U_DATA - wuser and ruser type
  //   U_RESP - buser type
  //   item_t - item type definition that matches interface -
  //            for some simulators is requied to have single point of
  //            type definition so in such case type can by pass to VIP
  class core #(
                int N=1,
                int I=1,
                int A=1,
                type U_REQ=logic[0:0],
                type U_DATA=logic[0:0],
                type U_RESP=logic[0:0],
                type item_t = gvip_aximm_item_pkg::item #(N, I, A, U_REQ, U_DATA, U_RESP)
              ) extends core_imp #(N, I, A, U_REQ, U_DATA, U_RESP, item_t);

    // Function: new
    //
    // Creates an instance of VIP core
    //
    // name     - instance name
    // vif      - AXI Memory Mapped interface handler
    // vclk     - clock interface handler
    // vip_type - one of VIPs type (MASTER/SLAVE/MONITOR)
    // vip_cfg  - optional cofiguration object (please check: gvip_config)
    //
    extern function new (string name,
                         virtual gaximm_if #(N, I, A, U_REQ, U_DATA, U_RESP) vif,
                         virtual gclk_if vclk,
                         gvip::type_e vip_type,
                         gvip_config vip_cfg = null);

    // Function: get_vip_type
    //
    // Returns type of VIP
    //
    extern virtual function gvip::type_e get_vip_type();

    // Function: get_config
    //
    // Returns current configuration object
    //
    extern virtual function gvip_config get_config();

    // Function: add_ap2pkt
    //
    // Use this function to register object with analysis port interface implementation,
    // ~write~ function from this interface will be called with full package
    // Any number of object can be register but the same object instance
    // will be given to all subscribers
    //
    extern virtual function void add_ap2pkt(gvip::channel_e channel,
                                            analysis_port_ic #(item_t) ap);

    // Function: add_ap2transfer
    //
    // Use this function to register object with analysis port interface implementation,
    // ~write~ function from this interface will be called with each transfer occurrence
    // Any number of object can be register but the same object instance
    // will be given to all subscribers
    //
    extern virtual function void add_ap2transfer(gvip::channel_e channel,
                                                 analysis_port_ic #(item_t) ap);

    // Function: set_policy
    //
    // Assign new handshake policy to VIP's channel
    //
    // channel - one of channels (AW/AR/W/R/B/AW_W)
    //           In case of AW_W the same policy will be apply to AW and AR channel
    // obj - policy object derived from gvip_policy_pkg::policy
    // do_randomize_policy - if set, VIP will call randomize method at policy object,
    //                       usefull when policy is created without declaration e.g.:
    //                       vip.set_policy(gvip_policy_pkg::random::create("def_random"), 1);
    // clone - in default VIP will clone policy to operate on it
    //
    extern virtual function void set_policy(gvip::channel_e channel, policy obj,
                                            bit do_randomize_policy = 0, bit clone = 1);

    // Function: send_item
    //
    // This function sends data item to AxiMM interface
    // If some package is currently trasmited, new item will be added to queue
    // Depending on ~tr_type~ in item object transaction will be posterd at proper channel
    //
    extern virtual function void send_item(item_t item);

    // Function: send_aw
    //
    // This function sends data item at AxiMM AW channel
    // If some package is currently trasmited, new item will be added to queue
    //
    extern virtual function void send_aw(item_t item);

    // Function: send_w
    //
    // This function sends data item at AxiMM W channel
    // If some package is currently trasmited, new item will be added to queue
    //
    extern virtual function void send_w(item_t item);

    // Function: send_b
    //
    // This function sends data item at AxiMM B channel
    // If some package is currently trasmited, new item will be added to queue
    //
    extern virtual function void send_b(item_t item);

    // Function: send_ar
    //
    // This function sends data item at AxiMM AR channel
    // If some package is currently trasmited, new item will be added to queue
    //
    extern virtual function void send_ar(item_t item);

    // Function: send_r
    //
    // This function sends data item at AxiMM R channel
    // If some package is currently trasmited, new item will be added to queue
    //
    extern virtual function void send_r(item_t item);

    // Function: run_phase
    //
    // Main VIPs service loop - run VIPs processing (must be called by test)
    // This task spawn internal processes and return immediately
    // Spawned processes are endless unless ~gvip_config::stop_vip~ is set
    //
    extern virtual task run_phase();

    // Function: clean
    //
    // This function clean VIP
    // Brakes any transfers at interface, clear all queues and any data structures
    //
    extern virtual function void clean();

  endclass


